    lh(back2, (0.24, -0.36, 1.12), (0.6, 0.4, -0.6))
    up = T(hips=(0, -0.06, -0.05), hr=(-5, 0, -14), sp=(-4, 0, -5), ch=(-6, 0, -4), nod=5, fL=(0.06, -0.24, 0.05), fLr=(8, -6, 0), fR=FR, fRr=FRr)
