    k1 = slash_keys(1, quick=True)          # f7 wind, f9 wind2, f11 hit, f13 follow
    back = T(hips=(0.04, -0.14, -0.13), hr=(7, 0, 6), sp=(3, 0, 0), ch=(2, 0, -6), fL=(0.06, -0.26, 0), fLr=FLr, fR=(-0.08, 0.20, 0.02), fRr=(-30, 12, 0))
