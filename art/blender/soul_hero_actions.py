        sword(dip, (-0.32, -0.22, 1.05), (0.20, -0.60, 0.75), (0.1, -0.75, -0.6), hint=(-0.5, 0.7, -0.5))
        lh(dip, (0.20, -0.36, 1.12), (0.6, 0.4, -0.7))
