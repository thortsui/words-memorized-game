"""魂系主角的 11 個手刻動作。全部原地播放（Root 不動，位移由遊戲程式負責），單發動作起訖都是戒備姿勢。
座標：-Y 前、+X 角色左、+Z 上；位置單位公尺（主角身高 1.8）。
命中格（30fps）：Slash f15、HeavySlash f24、Combo f11／f20／f33、Parry f7、Guard f6。
"""
import math
from mathutils import Vector
from soul_humanoid_anim import W, HW


def build(rig, only=None):
    P = rig.P

    def T(hips=(0, 0, 0), hr=(0, 0, 0), sp=(0, 0, 0), ch=(0, 0, 0), look=0.0, nod=0.0, **kw):
        """軀幹姿勢；頭頸自動補償，讓臉維持朝向 look（度，正＝左）並保持水平。"""
        yaw = max(-75, min(75, look - (hr[2] + sp[2] + ch[2])))
        pit = nod - 0.7 * (hr[0] + sp[0] + ch[0])
        rol = -0.6 * (hr[1] + sp[1] + ch[1])
        return P(hips=hips, hips_r=hr, spine=sp, chest=ch, neck=(pit * 0.4, rol * 0.4, yaw * 0.4),
                 head=(pit * 0.6, rol * 0.6, yaw * 0.6), **kw)

    def sword(Pd, grip, blade, edge, hint=None):
        return rig.reach(Pd, "R", grip, hint, Vector(blade).normalized(), Vector(edge))

    def sw(Pd, grip, a, z=0.0, cw=False, hint=None, tilt=0.0):
        """水平揮砍用：a 為刃的方位角（0＝指向右、90＝正前、180＝指向左），刃口朝揮動方向。"""
        ar = math.radians(a)
        blade = Vector((-math.cos(ar), -math.sin(ar), z)).normalized()
        edge = Vector((math.sin(ar), -math.cos(ar), tilt))
        if cw:
            edge = -edge
        return rig.reach(Pd, "R", grip, hint, blade, edge)

    def lh(Pd, pos, hint=None):
        return rig.reach(Pd, "L", pos, hint)

    def A(name, keys, loop=False):
        if only and name not in only:
            return
        rig.action(name, keys, loop)

    FL, FLr, FR, FRr = (0.06, -0.20, 0), (8, 0, 0), (-0.08, 0.22, 0), (-40, 0, 0)

    def guard(dz=0.0, lean=0.0, tip=0.0):
        g = T(hips=(0, 0, -0.07 + dz), hr=(5 + lean, 0, -22), sp=(4 + lean * 0.5, 0, -6), ch=(4 + lean * 0.5, 0, -5),
              fL=FL, fLr=FLr, fR=FR, fRr=FRr)
        sword(g, (-0.24, -0.30, 1.00 + dz * 0.7), (0.28, -0.62, 0.73 + tip), (0.1, -0.75, -0.6), hint=(-0.5, 0.7, -0.5))
        lh(g, (0.22, -0.30, 1.12 + dz * 0.8), (0.6, 0.4, -0.7))
        return g
    G = guard()
    rig.base = G

    # ---------------------------------------------------------------- Idle：持劍戒備、呼吸
    A("Idle", [(1, G), (24, guard(-0.008, 0.6, -0.02)), (44, guard(-0.016, 1.6, -0.05)), (66, guard(-0.006, 0.5, -0.015)), (81, G)], loop=True)

    # ---------------------------------------------------------------- Walk：向左側移繞行（原地循環，名目速度約 0.45 m/s）
    N = 32; stride = 0.48
    keys = []
    for f in range(1, N + 2, 2):
        ph = ((f - 1) / N) % 1.0

        def foot(p, base, lift=0.07, sw_=0.34):
            p = p % 1.0
            if p < sw_:
                t = p / sw_
                st = t * t * (3 - 2 * t)
                x = -stride / 2 + stride * st
                z = lift * math.sin(math.pi * t)
                pit = 10 * math.sin(math.pi * t)
            else:
                t = (p - sw_) / (1 - sw_)
                x = stride / 2 - stride * t
                z = 0; pit = 0
            return (base[0] + x, base[1], base[2] + z), pit
        pl, pitl = foot(ph, FL)
        pr, pitr = foot(ph + 0.5, FR)
        bob = -0.012 * math.cos(4 * math.pi * ph)
        sway = 0.025 * math.sin(2 * math.pi * (ph - 0.12))
        k = T(hips=(sway, 0, -0.085 + bob), hr=(5, 2.0 * math.sin(2 * math.pi * ph), -22 + 3 * math.sin(2 * math.pi * ph)),
              sp=(4, -1.5 * math.sin(2 * math.pi * ph), -6), ch=(4, 0, -5),
              fL=pl, fLr=(8, pitl, 0), fR=pr, fRr=(-40, pitr, 0))
        sword(k, (-0.24 + sway * 0.6, -0.30, 0.99 + bob * 0.6), (0.28, -0.62, 0.73 + 0.03 * math.sin(4 * math.pi * ph)), (0.1, -0.75, -0.6),
              hint=(-0.5, 0.7, -0.5))
        lh(k, (0.22 + sway * 0.6, -0.30, 1.11 + bob * 0.6), (0.6, 0.4, -0.7))
        keys.append((f, k))
    A("Walk", keys, loop=True)

    # ---------------------------------------------------------------- Slash：橫斬（右 → 左）
