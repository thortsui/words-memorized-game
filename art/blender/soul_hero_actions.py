"""魂系主角的手刻動作（第二版：曲線緩動、預備→爆發→跟隨→回復、肢體時間差、地面約束）。
全部原地播放（Root 不動，位移由遊戲程式負責），單發動作起訖都是戒備姿勢 G。片段一律從第 0 格開始（30fps）。
座標：-Y 前、+X 角色左、+Z 上；位置單位公尺（主角身高 1.8）。
keys 第三欄是「抵達該格」那段的緩動：in＝加速抵達（揮擊爆發）、out＝減速抵達（跟隨、回勢）、io＝平滑。
hits＝命中標記格，實際命中時間由 Rig.action 依劍尖速度峰值量出，寫進 rig.meta。
"""
import math
from mathutils import Vector
from soul_humanoid_anim import W, HW, gait


def build(rig, only=None):
    P = rig.P

    def T(hips=(0, 0, 0), hr=(0, 0, 0), sp=(0, 0, 0), ch=(0, 0, 0), look=0.0, nod=0.0, **kw):
        """軀幹姿勢；頭頸自動補償，讓臉維持朝向 look（度，正＝左）並保持水平。"""
        yaw = max(-75, min(75, look - (hr[2] + sp[2] + ch[2])))
        pit = nod - 0.7 * (hr[0] + sp[0] + ch[0])
        rol = -0.6 * (hr[1] + sp[1] + ch[1])
        return P(hips=hips, hips_r=hr, spine=sp, chest=ch, neck=(pit * 0.4, rol * 0.4, yaw * 0.4),
                 head=(pit * 0.6, rol * 0.6, yaw * 0.6), **kw)

    def sword(Pd, grip, blade, edge, hint=None):
        return rig.reach(Pd, "R", grip, hint, Vector(blade).normalized(), Vector(edge))

    def sw(Pd, grip, a, z=0.0, cw=False, hint=None, tilt=0.0):
        """水平揮砍用：a 為刃的方位角（0＝指向右、90＝正前、180＝指向左），刃口朝揮動方向。"""
        ar = math.radians(a)
        blade = Vector((-math.cos(ar), -math.sin(ar), z)).normalized()
        edge = Vector((math.sin(ar), -math.cos(ar), tilt))
        if cw:
            edge = -edge
        return rig.reach(Pd, "R", grip, hint, blade, edge)

    def lh(Pd, pos, hint=None):
        return rig.reach(Pd, "L", pos, hint)

    def A(name, keys, loop=False, hits=None, lag=None):
        if only and name not in only:
            return
        rig.action(name, keys, loop, hits=hits, lag=lag)

    FL, FLr, FR, FRr = (0.06, -0.20, 0), (8, 0, 0), (-0.08, 0.22, 0), (-40, 0, 0)

    def guard(dz=0.0, lean=0.0, tip=0.0, sx=0.0, yaw=0.0, roll=0.0):
        g = T(hips=(sx, 0, -0.07 + dz), hr=(5 + lean, roll, -22 + yaw), sp=(4 + lean * 0.5, -roll * 0.5, -6), ch=(4 + lean * 0.5, 0, -5),
              fL=FL, fLr=FLr, fR=FR, fRr=FRr)
        sword(g, (-0.24 + sx * 0.7, -0.30, 1.00 + dz * 0.7), (0.28, -0.62, 0.73 + tip), (0.1, -0.75, -0.6), hint=(-0.5, 0.7, -0.5))
        lh(g, (0.22 + sx * 0.7, -0.30, 1.12 + dz * 0.8), (0.6, 0.4, -0.7))
        return g
    G = guard()
    rig.base = G

    # ---------------------------------------------------------------- Idle：持劍戒備、呼吸、重心左右換腳（3 秒循環）
    A("Idle", [(0, G), (22, guard(-0.010, 0.8, -0.02, 0.014, 1.5, 1.2)), (45, guard(-0.018, 1.8, -0.05, 0.0, 0.0, 0.0)),
               (68, guard(-0.008, 0.6, -0.015, -0.014, -1.5, -1.2)), (90, G)], loop=True)

    # ---------------------------------------------------------------- 步態共用：持劍戒備移動
    def move_cycle(N, stride, lift, swing, d, bob=0.012, sway=0.022, lean=0.0, step=2, dz=-0.085, twist=3.0):
        keys = []
        for f in range(0, N + 1, step):
            ph = (f / N) % 1.0
            gl = gait(ph, stride, lift, swing, d)
            gr = gait(ph + 0.5, stride, lift, swing, d)
            b = -bob * math.cos(4 * math.pi * ph)
            sx = sway * math.sin(2 * math.pi * (ph - 0.12))
            s2 = math.sin(2 * math.pi * ph)
            k = T(hips=(sx, 0, dz + b), hr=(5 + lean, 2.0 * s2, -22 + twist * s2), sp=(4 + lean * 0.5, -1.5 * s2, -6 - twist * 0.5 * s2), ch=(4, 0, -5),
                  fL=(FL[0] + gl[0], FL[1] + gl[1], gl[2]), fLr=(8, gl[3], 0), fR=(FR[0] + gr[0], FR[1] + gr[1], gr[2]), fRr=(-40, gr[3], 0))
            sword(k, (-0.24 + sx * 0.6, -0.30, 1.0 + dz + 0.085 + b * 0.6), (0.28, -0.62, 0.73 + 0.03 * math.sin(4 * math.pi * ph)), (0.1, -0.75, -0.6),
                  hint=(-0.5, 0.7, -0.5))
            lh(k, (0.22 + sx * 0.6, -0.30, 1.11 + dz + 0.085 + b * 0.6), (0.6, 0.4, -0.7))
            keys.append((f, k))
        return keys

    # Walk：向左側移繞行（原地循環，名目速度約 0.45 m/s）——沿用原契約
    A("Walk", move_cycle(32, 0.46, 0.07, 0.36, (1.0, 0.0)), loop=True)
    # StrafeL／StrafeR：戒備橫移（不交叉步，較低重心）
    A("StrafeL", move_cycle(28, 0.30, 0.06, 0.40, (1.0, 0.0), sway=0.03, dz=-0.10, twist=2.0), loop=True)
    A("StrafeR", move_cycle(28, 0.30, 0.06, 0.40, (-1.0, 0.0), sway=0.03, dz=-0.10, twist=2.0), loop=True)

    # ---------------------------------------------------------------- Run：前傾快跑、劍垂在右後方、左臂擺動（20 格循環）
    N = 20
    keys = []
    for f in range(0, N + 1, 2):
        ph = f / N
        gl = gait(ph, 0.80, 0.17, 0.58, (0, -1), pitch=22)
        gr = gait(ph + 0.5, 0.80, 0.17, 0.58, (0, -1), pitch=22)
        s2 = math.sin(2 * math.pi * ph)
        b = 0.035 * math.cos(4 * math.pi * (ph - 0.08))
        k = T(hips=(0.018 * s2, 0, -0.13 + b), hr=(15, 2.5 * s2, 9 * s2), sp=(5, -1.5 * s2, -7 * s2), ch=(3, 0, -8 * s2), look=0, nod=-6,
              fL=(0.08 + gl[0], -0.02 + gl[1], gl[2]), fLr=(4, gl[3], 0), fR=(-0.08 + gr[0], 0.02 + gr[1], gr[2]), fRr=(-4, gr[3], 0),
              kL=(0, -0.3, 0), kR=(0, -0.3, 0))
        sword(k, (-0.30 - 0.02 * s2, -0.02 + 0.10 * s2, 0.92 + b * 0.5), (-0.20, 0.80, -0.45), (0, -0.4, -0.9), hint=(-0.7, 0.4, -0.5))
        lh(k, (0.24, -0.16 - 0.24 * s2, 1.00 + 0.08 * abs(s2) + b * 0.5), (0.7, 0.4, -0.5))
        keys.append((f, k))
    A("Run", keys, loop=True)

    # ---------------------------------------------------------------- Slash：橫斬（右 → 左）。預備（扭腰蓄力）→ 弧線爆發 → 跟隨過頭 → 回勢
