    dive = T(hips=(0.03, -0.10, -0.34), hr=(38, 0, 26), sp=(18, 0, 0), ch=(14, 0, 0), nod=20, fL=(0.10, -0.26, 0), fLr=(20, 0, 0), fR=(-0.06, 0.20, 0.04), fRr=(-20, 30, 0))
