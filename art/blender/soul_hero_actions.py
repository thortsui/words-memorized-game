    chop = T(hips=(0, -0.30, -0.24), hr=(24, 0, 10), sp=(11, 0, 4), ch=(9, 0, 6), nod=8, fL=(0.06, -0.56, 0), fLr=FLr, fR=(-0.08, 0.22, 0.03), fRr=(-30, 22, 0))
