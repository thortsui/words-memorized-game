    A("Slash", [(0, G), (4, s_dip, "io"), (10, s_wind, "out"), (13, s_wind2, "io"), (16, s_mid, "in"), (18, s_hit, "lin"), (22, s_fol, "out3"),
                (29, s_set, "io"), (42, G, "io")], hits=[18])

