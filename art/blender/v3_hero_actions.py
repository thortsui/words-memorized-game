"""單字魂 v3 主角動作（從 soul_hero_actions.py 複製再改：Idle 改成劍尖朝下前方的休息戒備、站距 0.19H；Victory 配合 0.60H 的劍重新拄地）。
原說明（第二版：曲線緩動、預備→爆發→跟隨→回復、肢體時間差、地面約束）。
全部原地播放（Root 不動，位移由遊戲程式負責），單發動作起訖都是戒備姿勢 G。片段一律從第 0 格開始（30fps）。
座標：-Y 前、+X 角色左、+Z 上；位置單位公尺（主角身高 1.8）。
keys 第三欄是「抵達該格」那段的緩動：in＝加速抵達（揮擊爆發）、out＝減速抵達（跟隨、回勢）、io＝平滑。
hits＝命中標記格，實際命中時間由 Rig.action 依劍尖速度峰值量出，寫進 rig.meta。
"""
import math
from mathutils import Vector, Quaternion
from soul_humanoid_anim import W, HW, gait


def build(rig, only=None):
    P = rig.P

    def T(hips=(0, 0, 0), hr=(0, 0, 0), sp=(0, 0, 0), ch=(0, 0, 0), look=0.0, nod=0.0, **kw):
        """軀幹姿勢；頭頸自動補償，讓臉維持朝向 look（度，正＝左）並保持水平。"""
        yaw = max(-75, min(75, look - (hr[2] + sp[2] + ch[2])))
        pit = nod - 0.7 * (hr[0] + sp[0] + ch[0])
        rol = -0.6 * (hr[1] + sp[1] + ch[1])
        return P(hips=hips, hips_r=hr, spine=sp, chest=ch, neck=(pit * 0.4, rol * 0.4, yaw * 0.4),
                 head=(pit * 0.6, rol * 0.6, yaw * 0.6), **kw)

    def sword(Pd, grip, blade, edge, hint=None):
        return rig.reach(Pd, "R", grip, hint, Vector(blade).normalized(), Vector(edge))

    def sw(Pd, grip, a, z=0.0, cw=False, hint=None, tilt=0.0):
        """水平揮砍用：a 為刃的方位角（0＝指向右、90＝正前、180＝指向左），刃口朝揮動方向。"""
        ar = math.radians(a)
        blade = Vector((-math.cos(ar), -math.sin(ar), z)).normalized()
        edge = Vector((math.sin(ar), -math.cos(ar), tilt))
        if cw:
            edge = -edge
        return rig.reach(Pd, "R", grip, hint, blade, edge)

    def lh(Pd, pos, hint=None):
        return rig.reach(Pd, "L", pos, hint)

    def A(name, keys, loop=False, hits=None, lag=None, cancel=None):
        if only and name not in only:
            return
        if cancel is None:
            rig.action(name, keys, loop, hits=hits, lag=lag)
        else:
            rig.action(name, keys, loop, hits=hits, lag=lag, cancel=cancel)

    FL, FLr, FR, FRr = (0.06, -0.20, 0), (8, 0, 0), (-0.08, 0.22, 0), (-40, 0, 0)

    def guard(dz=0.0, lean=0.0, tip=0.0, sx=0.0, yaw=0.0, roll=0.0):
        g = T(hips=(sx, 0, -0.07 + dz), hr=(5 + lean, roll, -22 + yaw), sp=(4 + lean * 0.5, -roll * 0.5, -6), ch=(4 + lean * 0.5, 0, -5),
              fL=FL, fLr=FLr, fR=FR, fRr=FRr)
        sword(g, (-0.24 + sx * 0.7, -0.30, 1.00 + dz * 0.7), (0.28, -0.62, 0.73 + tip), (0.1, -0.75, -0.6), hint=(-0.5, 0.7, -0.5))
        lh(g, (0.22 + sx * 0.7, -0.30, 1.12 + dz * 0.8), (0.6, 0.4, -0.7))
        return g
    G = guard()
    rig.base = G

