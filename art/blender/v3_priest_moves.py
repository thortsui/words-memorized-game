PITCH_MAX = 13.0                 # 骨盆前傾上限（度）：超過的部分移到脊椎／胸
CLEAR = 0.035                    # 冰晶裙最低點離地（公尺）


def shard_safe(kw):
    """二階冰晶裙 P2_IceShards 剛性綁在 Hips：rest 時最低點 0.26 m、在骨盆下方 1.01 m，前緣半徑 0.56 m、側緣 1.3 m、後緣 0.58 m（z 0.33）。
    骨盆下沉或前傾太多會把冰刺插進地面，所以：骨盆前傾超過 PITCH_MAX 的部分改由脊椎／胸承擔（總前傾不變），
    再依剩下的骨盆角度算出允許的最大下沉量，必要時把骨盆抬高。Sweep 一階起、二階也會用，所以五招都套用。"""
    import math
    hips = list(kw.get("hips", (0, 0, 0))); hr = list(kw.get("hr", (0, 0, 0)))
    sp = list(kw.get("sp", (0, 0, 0))); ch = list(kw.get("ch", (0, 0, 0)))
    if hr[0] > PITCH_MAX:
        ex = hr[0] - PITCH_MAX
        hr[0] = PITCH_MAX; sp[0] += ex * 0.6; ch[0] += ex * 0.4
    p = math.radians(hr[0]); r = math.radians(abs(hr[1]))
    drop_f = 0.564 * math.sin(max(p, 0)) + 1.01 * (1 - math.cos(p))
    drop_b = 0.584 * math.sin(max(-p, 0)) + 1.01 * (1 - math.cos(p)) - 0.07
    drop_s = 1.30 * math.sin(r) + 1.01 * (1 - math.cos(r))
    room = 0.259 - CLEAR - max(drop_f, drop_b, drop_s)          # 骨盆還能往下沉多少（公尺）
    z = hips[2]
    eff = z * 0.55 if -0.40 < z < 0 else z                       # 同 v3_priest_actions.T 的 55% 下沉
    if eff * U < -room:
        eff = -room / U
        z = eff / 0.55 if eff > -0.22 else eff
    hips[2] = z
    kw.update(hips=tuple(hips), hr=tuple(hr), sp=tuple(sp), ch=tuple(ch))
    return kw


