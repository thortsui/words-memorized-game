R = None
BODY = None
HH = 1.0
U = 1.0


def setup(rig, body, h):
    global R, BODY, HH, U
    R, BODY, HH, U = rig, body, h, body.U


def hx(x, y, z):
    return (x * HH / U, y * HH / U, z * HH / U)


def cv(p):
    m = Vector(p) * 1.278
    piv2 = Vector((0, 0, 1.918)); piv3 = Vector((0, 0.005 * HH, 0.770 * HH))
    q = piv3 + (m - piv2) * 0.93
    return tuple(q / U)


def two(Pd, Rp, Lp, edge_=(0, -1, 0), hintR=None, elL=None, raw=False):
    """v2a 語意的 (Rp, Lp)：Lp→Rp 是戟頭方向。v3：右手到 Lp、左手到 Rp。"""
    if not raw:
        Rp, Lp = cv(Rp), cv(Lp)
    Rp = Vector(Rp); Lp = Vector(Lp)
    d = Rp - Lp
    Pd["ikL"] = 1.0; Pd["gripL"] = d.length
    if elL:
        Pd["elL"] = elL
    R.reach(Pd, "R", tuple(Lp), hintR, d.normalized(), Vector(edge_))


def one(Pd, g, d, edge_, left, hintR=None, hintL=None, raw=False):
    if not raw:
        g, left = cv(g), cv(left)
    Pd["ikL"] = 0.0
    R.reach(Pd, "R", g, hintR, Vector(d).normalized(), Vector(edge_))
    R.reach(Pd, "L", left, hintL)


