KEYFRAMES = {}


def P(*ds):
    out = {}
    for d in ds:
        out.update(d)
    return out


def LR(d):
    """{'Wing1': (左值, 右值)}，右值也用「左邊的寫法」（自動把 Y、Z 反號）。單一值＝左右對稱。"""
    out = {}
    for k, v in d.items():
        if isinstance(v[0], (tuple, list)):
            lv, rv = v
        else:
            lv = rv = v
        out[k + ".L"] = tuple(lv)
        out[k + ".R"] = (rv[0], -rv[1], -rv[2]) + tuple(rv[3:])
    return out


def ik(bone, l, r=None):
    """手腳 IK 位移：右邊用左邊的寫法（X 自動反號）。"""
    r = l if r is None else r
    l = tuple(l) + (0,) * (4 - len(l))
    r = tuple(r) + (0,) * (4 - len(r))
    return {bone + ".L:ik": l, bone + ".R:ik": (-r[0],) + r[1:]}


def H(l, r=None):
    return ik("Hand", l, r)


def F(l, r=None):
    return ik("Foot", l, r)


PLANT = (0, 0, 0, 0)


def setup_front_ik(A):
    for sx in (".L", ".R"):
        A.add_leg("UpperArm" + sx, "ForeArm" + sx, ["Hand" + sx, "Fingers" + sx], "Hand" + sx + ":ik")


def act(A, name, keys, hits, cancel, keyframes, lag=None):
    A.action(name, keys, lag=lag or LAG, hits=hits)
    A.meta[name]["cancel"] = round(cancel / FPS, 3)
    KEYFRAMES[name] = keyframes


